/**
 * [TD-37] Оговорки о качестве обработки звонка (S2).
 *
 * Политика пайплайна — «degrade, don't die»: фатален только STT дорожки
 * владельца, всё остальное деградирует и записывает результат частично.
 * Раньше такие состояния жили только в логе, и пользователь не отличал
 * «в звонке правда один голос» от «системная дорожка не разделилась».
 *
 * Коды стабильны — они лежат в БД (`calls.degraded_flags`) и приходят во
 * фронтенд как есть; расшифровка живёт в локалях.
 */
export type DegradedFlag =
  /** Расшифрованы не все чанки — транскрипт собран из того, что удалось. */
  | 'partial_transcript'
  /** Системная дорожка не разделена на голоса: собеседники в одном спикере. */
  | 'system_track_not_diarized'
  /** Микрофонная дорожка не разделена на голоса (при включённой настройке). */
  | 'mic_track_not_diarized'
  /** Кластеризация голосов не отработала — спикеры остались анонимными. */
  | 'speaker_clustering_failed'
  /** Язык звонка определён, но пере-расшифровка под него не удалась. */
  | 'language_repin_failed';
