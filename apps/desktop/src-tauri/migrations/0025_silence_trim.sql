-- 0025 [T5/R14]: точка реза тихого хвоста у авто-остановленной записи.
--
-- Запись, которую забыли остановить, живёт часами: `duration_sec` считается по
-- wall-clock, а chunked-пайплайн каждые 10 минут гонит тишину через whisper и
-- добирает галлюцинации в транскрипт и рекап. R14 разрешает остановить такую
-- запись самим и отрезать тихий хвост.
--
-- Колонка хранит смещение точки реза от начала записи в миллисекундах — то
-- есть длину, которую следует оставить. Пишется один раз в `stop_recording`
-- (только при авто-стопе), читается пайплайном: по ней подрезаются корневые
-- WAV и выбрасываются сегменты транскрипта, попавшие за рез.
--
-- Почему отдельная колонка, а не вывод из `duration_sec`: длительность
-- pause-subtracted и округлена до секунд, а рез идёт по той же шкале, что
-- таймстемпы чанков (wall-clock от начала записи, паузы включены). Смешивать
-- эти шкалы уже приходилось (см. `process_final_chunk`) — второй раз не надо.
--
-- NULL = запись остановлена руками, аудио не трогали. Это и есть значение для
-- всех существующих строк: резать прошлые записи задним числом мы не будем,
-- пользователь их уже слушал такими.
ALTER TABLE calls ADD COLUMN silence_trim_ms INTEGER;
