-- Обязательные базовые модули: три тумблера удалены из продукта.
--
-- `mic_diarization_enabled` — диаризация микрофона теперь всегда включена;
--   риск дробления голоса владельца закрывает relabel_owner_on_mic_full_file,
--   аварийный ограничитель остался в Labs («сколько голосов»).
-- `assistant.semantic_search` — файлы эмбеддера входят в обязательный набор,
--   поиск больше не деградирует молча до подстрочного.
-- `summary_speculative_decoding` — черновая модель тоже обязательна и
--   применяется всегда, когда лежит на диске. Тумблер был неработающим:
--   он ничего не скачивал, а резидентный сервер аргумент draft-модели вообще
--   не получал.
-- `local_engine_invite_dismissed` — ключ без единого потребителя в коде.
--
-- Модели с диска не трогаем (R12-bis): удаление гигабайтов — только явным
-- действием пользователя через «Освободить место».
DELETE FROM settings WHERE key IN (
  'mic_diarization_enabled',
  'assistant.semantic_search',
  'summary_speculative_decoding',
  'local_engine_invite_dismissed'
);
