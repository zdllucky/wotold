-- 0028 [perm-usage]: отметка «Screen Capture у пользователя уже спрашивали».
--
-- `CGPreflightScreenCaptureAccess` возвращает false и когда пользователь
-- отказал, и когда его ни разу не спрашивали — различить их без приватных API
-- нельзя. Флаг закрывает это со стороны приложения: пока его нет, `denied` от
-- сайдкара показывается как «не запрошено», чтобы свежая установка не пугала
-- красным отказом на разрешении, которого никто не просил.
--
-- Для существующих установок такой умолчательный ответ был бы враньём в
-- обратную сторону: там доступ реально запрашивали, и настоящее «отказано»
-- превратилось бы в «не запрошено» — вместе с ним исчезли бы и подсказка про
-- протухший грант, и кнопка сброса, то есть ровно то, зачем пользователь на
-- этот экран и пришёл.
--
-- Признак «установка не новая» — наличие хотя бы одного звонка: записать его,
-- не пройдя через запрос разрешений, невозможно (`start_recording` делает
-- pre-check и без обоих грантов не стартует). На чистой базе таблица пуста,
-- строка не появляется, и новая установка получает честное «не запрошено».
INSERT INTO settings (key, value)
SELECT 'permissions.screen_capture_asked', '1'
WHERE EXISTS (SELECT 1 FROM calls)
ON CONFLICT(key) DO NOTHING;
