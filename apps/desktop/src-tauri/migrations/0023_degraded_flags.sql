-- 0023 [TD-37]: персистентные degraded-флаги на звонке.
--
-- Политика «degrade, don't die» проведена по всему пайплайну последовательно:
-- фатален только STT дорожки владельца, а диаризация, кластеры, авто-привязка,
-- рекап и эмбеддинги деградируют с warn'ом и записью того, что успели. Проблема
-- в том, что все эти состояния жили ТОЛЬКО в логе: пользователь не отличал
-- «в звонке правда один голос» от «система-дорожка не разделилась и всё ушло в
-- speaker:0», а разработчик — «частичный транскрипт» от «полного».
--
-- Флаги хранятся JSON-массивом кодов в одной колонке, а не таблицей: их читают
-- всегда целиком и всегда для одного звонка, а писать их приходится из середины
-- пайплайна, где лишний INSERT в связанную таблицу — ещё одна точка отказа на
-- пути, который и так уже деградировал.
--
-- NULL и '[]' значат одно и то же — «оговорок нет»; NULL для существующих строк
-- backfill'ом не трогаем: у старых звонков этой информации просто нет, и
-- выдумывать её нельзя.
ALTER TABLE calls ADD COLUMN degraded_flags TEXT;
