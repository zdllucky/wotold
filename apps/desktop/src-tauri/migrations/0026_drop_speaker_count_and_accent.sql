-- Две настройки, потерявшие смысл.
--
-- `mic_diarization_num_speakers` — ручное «сколько собеседников». Он был
--   костылём вокруг потолка в три спикера: реальные четвёртый и пятый молча
--   приписывались другим людям, и единственным выходом было задать число
--   руками. Потолок поднят до санитарных десяти, число кластеров определяет
--   сам диаризатор — переопределять больше нечего.
-- `ui.accent` — выбор акцента из прошлого поколения дизайна. Пикер убран в B18.5,
--   в токенах нет ни одного блока [data-accent], то есть значение писалось
--   в никуда.
DELETE FROM settings WHERE key IN (
  'mic_diarization_num_speakers',
  'ui.accent'
);
