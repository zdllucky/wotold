//! [M15.4] Классификатор генеративных запросов (SPEC §1 хендоффа).
//!
//! Ассистент только ищет и разбирает — «напиши/составь/сгенерируй…» получают
//! отказ ДО retrieval. Без LLM и без regex-крейта: точные словоформы
//! (императив ± «те» + инфинитив) по границам слов. Прошедшее время
//! («что мы написали», «кто отправил») — это вопросы-поиск, НЕ генерация.

// [M15.4] Production caller — assistant::ask (M15.7).
#![allow(dead_code)]

/// Императивы (2-е лицо ед.ч.); форма на «-те» матчится автоматически.
const IMPERATIVES: &[&str] = &[
    "напиши",
    "составь",
    "сгенерируй",
    "сгенерь",
    "придумай",
    "переведи",
    "отправь",
    "создай",
    "запланируй",
    "оформи",
    "нарисуй",
];

/// Инфинитивы («надо написать письмо» — тоже генерация).
const INFINITIVES: &[&str] = &[
    "написать",
    "составить",
    "сгенерировать",
    "придумать",
    "перевести",
    "отправить",
    "создать",
    "запланировать",
    "оформить",
    "нарисовать",
];

/// Генеративный ли запрос. Слова сравниваются целиком (не подстрокой):
/// «написали»/«отправил»/«создали» — прошедшее время, не матчится.
pub fn is_generative(question: &str) -> bool {
    question
        .to_lowercase()
        .split(|c: char| !c.is_alphabetic())
        .filter(|w| !w.is_empty())
        .any(is_generative_word)
}

fn is_generative_word(word: &str) -> bool {
    if INFINITIVES.contains(&word) {
        return true;
    }
    let plural_base = word.strip_suffix("те");
    IMPERATIVES
        .iter()
        .any(|imp| word == *imp || plural_base == Some(*imp))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Позитивы: маркеры SPEC §1 + примеры мока.
    #[test]
    fn generative_requests_are_flagged() {
        let positives = [
            "Напиши фоллоу-ап письмо Арману по итогам синхрона", // мок WK_AS_STORE
            "напиши письмо",
            "Напишите официальный ответ юристам",
            "Составь план на неделю",
            "составьте протокол встречи",
            "Сгенерируй саммари для рассылки",
            "придумай название для фичи",
            "Переведи рекап на английский",
            "переведите последний транскрипт",
            "Отправь итоги команде",
            "создай задачу в трекере",
            "Запланируй встречу с Контуром",
            "оформи решения в документ",
            "Нарисуй схему пайплайна",
            "надо написать письмо по итогам", // инфинитив
            "можешь составить отчёт по звонкам?",
            "хочу сгенерировать пост из рекапа",
            "прошу перевести транскрипт",
        ];
        for q in positives {
            assert!(is_generative(q), "должен быть отказ: {q}");
        }
    }

    /// Негативы: поиск/разбор, включая прошедшее время тех же глаголов.
    #[test]
    fn search_questions_pass_through() {
        let negatives = [
            "Какие задачи взял Дмитрий на этой неделе?",
            "Когда обсуждали приватность?",
            "Что обещали «Контуру» на демо?",
            "Решения планёрки продукта",
            "что мы написали в чате по срокам?", // прошедшее ≠ императив
            "кто отправил отчёт в пятницу?",
            "когда создали проект пилота?",
            "что придумали на брейншторме?",
            "кто составил план миграции?",
            "что перевели на прод в мае?",
            "какие письма мы отправляли клиенту?",
            "о чём договорились по нагрузочным?",
            "почему решили показывать локальный режим?",
            "переведён ли пилот на новый тариф?", // причастие
        ];
        for q in negatives {
            assert!(!is_generative(q), "не должен быть отказ: {q}");
        }
    }

    #[test]
    fn word_boundaries_and_case_are_respected() {
        // Подстрока внутри слова — не маркер.
        assert!(!is_generative("обсуждали переведённые документы"));
        assert!(!is_generative("какой состав участников был на демо?")); // «состав» = существительное
                                                                         // Регистр и пунктуация не мешают.
        assert!(is_generative("НАПИШИ, пожалуйста, письмо!"));
        assert!(is_generative("…и составь список"));
        // Пустое / без букв.
        assert!(!is_generative(""));
        assert!(!is_generative("12:30 ?!"));
    }
}
