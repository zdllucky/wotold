/**
 * Размер файла модели человеку.
 *
 * Гигабайты только когда их правда больше одного: раньше всё считалось в
 * гигабайтах с одним знаком, и мелкие модули (VAD 0.9 МБ, разделение голосов
 * 6 МБ, эмбеддер 26 МБ) показывались как «0.0 GB» — строки выглядели пустыми.
 */
export function formatBytes(bytes: number): string {
  if (bytes <= 0) return '—';
  if (bytes < 1024 ** 3) return `${Math.max(1, Math.round(bytes / 1024 ** 2))} MB`;
  return `${(bytes / 1024 ** 3).toFixed(1)} GB`;
}
