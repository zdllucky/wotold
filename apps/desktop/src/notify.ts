// [T7] Нативные уведомления ОС со строками из i18n.
//
// Плагин уведомлений живёт в Rust, поэтому текст мы отдаём туда командой, а не
// зовём JS-плагин: строки обязаны идти через `t()` и три локали (правило 4), а
// собранные в Rust они этого не умеют — до T7 `call_detect.rs` держал русские
// литералы, и казахский с английским видели русский баннер.
//
// Уведомление — дополнение к in-app баннеру, а не замена: баннер показывается
// когда окно активно, уведомление доносит то же самое когда оно свёрнуто.
// Поэтому отказ ОС в разрешении не считается ошибкой приложения и никогда не
// пробрасывается вызывающему.

import { invoke } from '@tauri-apps/api/core';

/**
 * Показать нативное уведомление. Никогда не бросает: вызывающие — обработчики
 * событий записи, и упавший баннер не должен ронять их логику.
 */
export async function notifyNative(title: string, body: string): Promise<void> {
  try {
    await invoke('show_notification', { title, body });
  } catch (e) {
    // Разрешение не выдано, плагин недоступен, окно уже закрыто — все эти
    // случаи для нас одинаковы: пользователь просто не увидит баннер ОС.
    console.warn('native notification failed', e);
  }
}
