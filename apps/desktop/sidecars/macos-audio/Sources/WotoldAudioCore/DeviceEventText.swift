import Foundation

/// [TD-44] Текст события «дорожка пропала» — один на обе дорожки.
///
/// Мотив прямой: до этого сообщение собиралось строкой прямо в
/// `AudioRecorder`, и когда такое же событие понадобилось системной дорожке,
/// текст пришлось бы писать второй раз. Так расходятся близнецы (правило 2):
/// одинаковый контракт, две независимые формулировки, и пользователь по
/// сообщению не понимает, одно это явление или разные.
///
/// Сам тип чистый — это единственная часть детекта потери устройства, которую
/// вообще можно проверить тестом: всё остальное упирается в Core Audio и
/// живое железо (правило 1 здесь честно не выполняется, и это записано в
/// TD-44).
public enum DeviceEventText {
    /// Как называется дорожка в сообщении пользователю.
    static func legName(_ leg: RotateLeg) -> String {
        switch leg {
        case .mic: return "микрофонная дорожка"
        case .system: return "системная дорожка"
        }
    }

    /// Чем объясняется пропажа — причины у дорожек разные.
    static func legCause(_ leg: RotateLeg) -> String {
        switch leg {
        case .mic: return "устройство ввода пропало или сменилось"
        case .system: return "устройство вывода сменилось или tap отвалился"
        }
    }

    /// Сообщение для `device_lost`. `silentSec` — сколько дорожка молчит.
    ///
    /// Отрицательное и нечисловое время не должно попадать в UI как
    /// «-0.0 с»: часы монотонные, но арифметика на них идёт через вычитание,
    /// и один неверный порядок аргументов у вызывающего давал бы бессмыслицу.
    public static func lost(leg: RotateLeg, silentSec: Double) -> String {
        let safe = silentSec.isFinite ? max(0, silentSec) : 0
        return "\(legName(leg)) молчит \(String(format: "%.1f", safe)) с — \(legCause(leg))"
    }
}
